export function normalizeElement(raw: string): string {
  const trimmed = raw.trim()
  if (/^\d+$/.test(trimmed)) {
    return ATOMIC_NUMBER_TO_SYMBOL[Number(trimmed)] ?? trimmed
  }
  const letters = trimmed.replace(/[^A-Za-z]/g, "")
  if (!letters) return trimmed
  if (letters.length >= 2) {
    const two = letters[0].toUpperCase() + letters[1].toLowerCase()
    if (two in ELEMENT_MASS) return two
  }
  const one = letters[0].toUpperCase()
  if (one in ELEMENT_MASS) return one
  return letters[0].toUpperCase() + letters.slice(1).toLowerCase()
}
